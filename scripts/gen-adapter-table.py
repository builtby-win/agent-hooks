#!/usr/bin/env python3
"""Regenerate the README "Supported Harnesses" table from builtin adapter.json files.

    scripts/gen-adapter-table.py          rewrite README.md in place
    scripts/gen-adapter-table.py --check  exit 1 if README.md is out of date (CI)

The table lives between <!-- adapters:start --> and <!-- adapters:end -->.
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README = os.path.join(ROOT, "README.md")
START, END = "<!-- adapters:start -->", "<!-- adapters:end -->"


def mechanism(op):
    kind = op["op"]
    shape = op.get("entry_shape")
    return f"{kind}, {shape}" if shape else kind


def row(d):
    v = d["versions"][d["default_version"]]
    paths, mechs = [], []
    for op in v.get("install", []):
        for p in op.get("paths") or ([op["stage_dir"]] if "stage_dir" in op else []):
            if p not in paths:
                paths.append(p)
        m = mechanism(op)
        if m not in mechs:
            mechs.append(m)
    aliases = ", ".join(f"`{a}`" for a in dict.fromkeys(d.get("aliases", [])) if a != d["id"])
    ident = f"`{d['id']}`" + (f" ({aliases})" if aliases else "")
    if d.get("unverified"):
        status = "Docs-only"
    else:
        tested = v.get("verified_against")
        status = f"Verified ({tested})" if tested else "Verified"
    return (
        d["display_name"],
        ident,
        ", ".join(f"`{p}`" for p in paths) or "-",
        "; ".join(f"`{m}`" for m in mechs) or "-",
        status,
    )


def table():
    adapters = [json.load(open(f)) for f in glob.glob(
        os.path.join(ROOT, "crates/agent-hooks-adapters/builtin/*/adapter.json"))]
    adapters.sort(key=lambda d: d["display_name"].lower())
    head = ("Harness", "Adapter ID", "Hook config written by installer", "Install mechanism", "Status")
    rows = [head] + [row(d) for d in adapters]
    lines = ["| " + " | ".join(r) + " |" for r in rows]
    lines.insert(1, "| " + " | ".join(":--" for _ in head) + " |")
    lines += [
        "",
        "`Verified` = exercised against the live CLI; the version in parentheses is the harness release last checked "
        "(`verified_against` in `adapter.json`). `Docs-only` = built from the published hook contract, never run live "
        "(`unverified: true`). Generated by `scripts/gen-adapter-table.py`; do not edit by hand.",
    ]
    return "\n".join(lines)


def main():
    text = open(README).read()
    try:
        a, rest = text.split(START, 1)
        _, b = rest.split(END, 1)
    except ValueError:
        sys.exit(f"README.md is missing {START} / {END} markers")
    new = f"{a}{START}\n{table()}\n{END}{b}"
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README adapter table is out of date: run scripts/gen-adapter-table.py")
        return
    open(README, "w").write(new)


main()
